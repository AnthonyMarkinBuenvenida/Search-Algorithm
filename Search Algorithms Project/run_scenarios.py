"""Run every test scenario and record the measured results.

    python run_scenarios.py

Writes results/measured_results.md. All figures come from this run, and timings
will differ from machine to machine and from run to run.
"""

from __future__ import annotations

import platform
from datetime import date
from pathlib import Path

from console import render
from sample_maps import sample_maps
from search import ALGORITHMS, GridMap, InvalidInputError, compare_all, run_search
from search.heuristics import HEURISTICS
from search.runner import comparison_rows, format_path, observations

OUTPUT = Path(__file__).parent / "results" / "measured_results.md"

INVALID_INPUTS = [
    ("Empty map", lambda: GridMap.from_text("")),
    ("Rows of different lengths", lambda: GridMap.from_text("S..\n..\n..G")),
    ("Unknown map character", lambda: GridMap.from_text("S.x\n..G")),
    ("Map with no goal", lambda: GridMap.from_text("S..\n...")),
    ("Map with two starts", lambda: GridMap.from_text("S.S\n..G")),
    ("Missing map file", lambda: GridMap.from_file("does_not_exist.txt")),
    ("Start outside the map", lambda: compare_all(GridMap.from_text("S.G"), start=(9, 9))),
    ("Goal on a wall", lambda: compare_all(GridMap.from_text("S#G"), goal=(0, 1))),
    ("Unknown algorithm", lambda: run_search("Dijkstra", GridMap.from_text("S.G"))),
]


def markdown_table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(str(value) for value in row) + " |" for row in rows]
    return lines


def scenario_section(number: int, title: str, path: Path) -> list[str]:
    grid = GridMap.from_file(path)
    results = compare_all(grid)
    valid = all(
        grid.is_valid_path(result.path, grid.start, grid.goal)
        for result in results.values()
        if result.found
    )

    lines = [f"## Scenario {number}: {title}", "", f"Map: `{path.name}`", "", "```text"]
    lines += [render(grid), "```", ""]
    lines += markdown_table(["Metric", *ALGORITHMS], comparison_rows(results))
    lines += ["", f"Every returned path passed the validity check: {'yes' if valid else 'NO'}."]
    lines += [f"- {note}" for note in observations(results)]
    lines += [""]
    for name, result in results.items():
        lines += [f"**{name} path:** {format_path(result.path, limit=10)}", ""]
    return lines


def invalid_section() -> list[str]:
    rows = []
    for label, action in INVALID_INPUTS:
        try:
            action()
        except InvalidInputError as error:
            rows.append([label, "Rejected cleanly", str(error)])
        else:
            rows.append([label, "NOT REJECTED", "-"])
    lines = ["## Scenario 6: Invalid map or input", ""]
    return lines + markdown_table(["Input", "Outcome", "Message shown"], rows) + [""]


def experiments_section() -> list[str]:
    """Show how node ordering and the heuristic change the results."""
    lines = ["## Effect of neighbour order on DFS", ""]
    rows = []
    for order in ("URDL", "RDLU", "DLUR", "LURD", "DRUL"):
        grid = GridMap.from_file(sample_maps()["Simple path"])
        grid.set_direction_order(order)
        result = run_search("DFS", grid)
        rows.append([order, result.nodes_explored, result.path_length])
    lines += ["Map: `1_simple_path.txt` (shortest possible path: 15 moves).", ""]
    lines += markdown_table(["Order", "Nodes explored", "Path length"], rows)

    lines += ["", "## Effect of the heuristic on A*", ""]
    lines += ["Map: `2_obstacle_filled.txt`.", ""]
    rows = []
    for heuristic in HEURISTICS:
        grid = GridMap.from_file(sample_maps()["Obstacle filled"])
        result = run_search("A*", grid, heuristic=heuristic)
        rows.append([
            heuristic, result.nodes_explored, result.path_cost, f"{result.execution_ms:.3f}",
        ])
    lines += markdown_table(["Heuristic", "Nodes explored", "Path cost", "Time (ms)"], rows)
    return lines + [""]


def main() -> None:
    lines = [
        "# Measured results",
        "",
        f"Generated by `run_scenarios.py` on {date.today()} with "
        f"Python {platform.python_version()} on {platform.system()}.",
        "Each time is the median of 5 runs, in milliseconds.",
        "",
    ]
    for number, (title, path) in enumerate(sample_maps().items(), start=1):
        lines += scenario_section(number, title, path)
    lines += invalid_section()
    lines += experiments_section()

    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
